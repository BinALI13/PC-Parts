const PDFDocument = require('pdfkit');

function generateCartPDF(cart, user) {
const doc = new PDFDocument({ size: 'A4', margin: 0 });

const pageWidth = doc.page.width;
const margin = 50;
const contentWidth = pageWidth - margin * 2;

const navy = '#172554';
const gold = '#d4a017';
const gray = '#6b7280';
const border = '#e5e7eb';
const bg = '#f8fafc';

doc.rect(0, 0, pageWidth, 130).fill(navy);

doc
.fillColor('#ffffff')
.fontSize(12)
.font('Helvetica-Bold')
.text('PC MARKET', margin, 35);

doc
.fillColor('#ffffff')
.fontSize(26)
.font('Helvetica-Bold')
.text('Order Receipt', margin, 58);

doc
.fillColor('#dbe4f0')
.fontSize(10)
.font('Helvetica')
.text('Thank you for shopping with PC Market', margin, 95);

let y = 160;

doc
.fillColor(navy)
.fontSize(15)
.font('Helvetica-Bold')
.text('Order Information', margin, y);

y += 30;

doc
.roundedRect(margin, y, contentWidth, 75, 8)
.fill(bg)
.stroke(border);

doc
.fillColor(gray)
.fontSize(9)
.font('Helvetica-Bold')
.text('CUSTOMER', margin + 20, y + 15);

doc
.fillColor(navy)
.fontSize(12)
.font('Helvetica')
.text(user ? user.username : 'Customer', margin + 20, y + 30);

doc
.fillColor(gray)
.fontSize(9)
.font('Helvetica-Bold')
.text('DATE', margin + 270, y + 15);

doc
.fillColor(navy)
.fontSize(12)
.font('Helvetica')
.text(new Date().toLocaleDateString(), margin + 270, y + 30);

y += 105;

doc
.fillColor(navy)
.fontSize(15)
.font('Helvetica-Bold')
.text('Products', margin, y);

y += 30;

let total = 0;
let number = 1;

cart.items.forEach(function(item) {
if (item.product) {
const product = item.product;

if (y > 680) {
doc.addPage();
y = 50;
}

doc
.roundedRect(margin, y, contentWidth, 65, 6)
.fill('#ffffff')
.stroke(border);

doc
.fillColor(gray)
.fontSize(10)
.font('Helvetica-Bold')
.text(number + '.', margin + 15, y + 20);

doc
.fillColor(navy)
.fontSize(12)
.font('Helvetica-Bold')
.text(product.productName, margin + 40, y + 15, {
width: 280
});

doc
.fillColor(gold)
.fontSize(12)
.font('Helvetica-Bold')
.text(Number(product.productPrice).toFixed(3) + ' BHD', pageWidth - margin - 130, y + 20, {
width: 110,
align: 'right'
});

total += Number(product.productPrice);
number++;
y += 75;
}
});

y += 10;

doc
.moveTo(margin, y)
.lineTo(pageWidth - margin, y)
.strokeColor(border)
.stroke();

y += 20;

doc
.fillColor(navy)
.fontSize(17)
.font('Helvetica-Bold')
.text('Total', margin, y);

doc
.fillColor(gold)
.fontSize(17)
.font('Helvetica-Bold')
.text(total.toFixed(3) + ' BHD', pageWidth - margin - 150, y, {
width: 150,
align: 'right'
});

const footerY = doc.page.height - 60;

doc
.moveTo(margin, footerY)
.lineTo(pageWidth - margin, footerY)
.strokeColor(border)
.stroke();

doc
.fillColor(gray)
.font('Helvetica')
.fontSize(8.5)
.text(
'Generated by PC Market - ' + new Date().toLocaleString(),
margin,
footerY + 12,
{ width: contentWidth, align: 'center' }
);

return doc;
}

module.exports = generateCartPDF;